
import { useState } from "react";

const initialOrders = [
  {
    id: "PO-2026-001",
    supplier: "TechNova Solutions",
    category: "Technology",
    item: "Cloud Infrastructure",
    quantity: 10,
    amount: 85000,
    date: "2026-11-10",
    delivery: "2026-11-25",
    status: "Approved",
    payment: "Pending",
  },
  {
    id: "PO-2026-002",
    supplier: "Global Materials Ltd",
    category: "Raw Materials",
    item: "Industrial Components",
    quantity: 50,
    amount: 120000,
    date: "2026-11-11",
    delivery: "2026-12-02",
    status: "Pending",
    payment: "Not Initiated",
  },
  {
    id: "PO-2026-003",
    supplier: "Swift Logistics",
    category: "Logistics",
    item: "Transportation Services",
    quantity: 5,
    amount: 32000,
    date: "2026-11-12",
    delivery: "2026-11-20",
    status: "Rejected",
    payment: "Not Initiated",
  },
];

const money = (value) =>
  new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(value);

export default function PurchaseOrders() {
  const [orders, setOrders] = useState(initialOrders);
  const [search, setSearch] = useState("");
  const [filter, setFilter] = useState("All");
  const [showForm, setShowForm] = useState(false);
  const [selectedOrder, setSelectedOrder] = useState(null);

  const [form, setForm] = useState({
    supplier: "",
    category: "Technology",
    item: "",
    quantity: 1,
    amount: "",
    delivery: "",
  });

  const updateForm = (e) => {
    setForm({ ...form, [e.target.name]: e.target.value });
  };

  const createOrder = (e) => {
    e.preventDefault();

    const newOrder = {
      id: `PO-2026-${String(orders.length + 1).padStart(3, "0")}`,
      supplier: form.supplier,
      category: form.category,
      item: form.item,
      quantity: Number(form.quantity),
      amount: Number(form.amount),
      date: new Date().toISOString().slice(0, 10),
      delivery: form.delivery,
      status: "Pending",
      payment: "Not Initiated",
    };

    setOrders([newOrder, ...orders]);
    setShowForm(false);
    setForm({
      supplier: "",
      category: "Technology",
      item: "",
      quantity: 1,
      amount: "",
      delivery: "",
    });
  };

  const updateStatus = (id, status) => {
    setOrders((previous) =>
      previous.map((order) =>
        order.id === id
          ? {
              ...order,
              status,
              payment:
                status === "Approved"
                  ? order.payment
                  : "Not Initiated",
            }
          : order
      )
    );

    setSelectedOrder(null);
  };

  const downloadPO = (order) => {
    const content = `
PROCURA PAY AI
PURCHASE ORDER

Order ID: ${order.id}
Date: ${order.date}

SUPPLIER
${order.supplier}

ORDER DETAILS
Item: ${order.item}
Category: ${order.category}
Quantity: ${order.quantity}
Total Amount: ${money(order.amount)}

Delivery Date: ${order.delivery}
Approval Status: ${order.status}
Payment Status: ${order.payment}

This is a demonstration purchase order generated by ProcuraPay AI.
    `;

    const blob = new Blob([content], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${order.id}.txt`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const filteredOrders = orders.filter((order) => {
    const matchesSearch =
      order.id.toLowerCase().includes(search.toLowerCase()) ||
      order.supplier.toLowerCase().includes(search.toLowerCase()) ||
      order.item.toLowerCase().includes(search.toLowerCase());

    const matchesFilter =
      filter === "All" || order.status === filter;

    return matchesSearch && matchesFilter;
  });

  const totalValue = orders.reduce((sum, order) => sum + order.amount, 0);
  const pendingCount = orders.filter(
    (order) => order.status === "Pending"
  ).length;
  const approvedCount = orders.filter(
    (order) => order.status === "Approved"
  ).length;

  const styles = {
    page: {
      color: "#e9edf7",
      padding: "28px",
      fontFamily: "inherit",
    },
    card: {
      background: "#151b2b",
      border: "1px solid #29334a",
      borderRadius: "14px",
      padding: "20px",
    },
    button: {
      background: "#7165f5",
      color: "white",
      border: "none",
      borderRadius: "9px",
      padding: "11px 17px",
      cursor: "pointer",
      fontWeight: 600,
    },
    input: {
      background: "#0f1524",
      border: "1px solid #35405a",
      color: "white",
      borderRadius: "8px",
      padding: "11px",
      width: "100%",
      boxSizing: "border-box",
    },
  };

  const statusStyle = (status) => ({
    display: "inline-block",
    padding: "5px 10px",
    borderRadius: "20px",
    fontSize: "12px",
    fontWeight: 600,
    background:
      status === "Approved"
        ? "#123d32"
        : status === "Pending"
        ? "#453719"
        : "#48242d",
    color:
      status === "Approved"
        ? "#56d6a0"
        : status === "Pending"
        ? "#f5c76a"
        : "#ff8294",
  });

  return (
    <div style={styles.page}>
      <div
        style={{
          display: "flex",
          justifyContent: "space-between",
          alignItems: "center",
          flexWrap: "wrap",
          gap: 15,
          marginBottom: 25,
        }}
      >
        <div>
          <h1 style={{ margin: 0, fontSize: 27 }}>
            Purchase Orders
          </h1>
          <p style={{ color: "#929db5", marginTop: 8 }}>
            Create, manage and track your procurement orders.
          </p>
        </div>

        <button
          style={styles.button}
          onClick={() => setShowForm(true)}
        >
          + Create Purchase Order
        </button>
      </div>

      {/* Summary cards */}
      <div
        style={{
          display: "grid",
          gridTemplateColumns: "repeat(auto-fit, minmax(190px, 1fr))",
          gap: 16,
          marginBottom: 25,
        }}
      >
        {[
          ["Total Orders", orders.length, "All purchase requests"],
          ["Total Order Value", money(totalValue), "Combined order value"],
          ["Pending Approval", pendingCount, "Awaiting review"],
          ["Approved Orders", approvedCount, "Ready for processing"],
        ].map(([label, value, description]) => (
          <div key={label} style={styles.card}>
            <p style={{ color: "#9ba6bd", margin: 0 }}>{label}</p>
            <h2 style={{ margin: "13px 0 7px", fontSize: 25 }}>
              {value}
            </h2>
            <small style={{ color: "#77849e" }}>{description}</small>
          </div>
        ))}
      </div>

      {/* Order table */}
      <div style={styles.card}>
        <div
          style={{
            display: "flex",
            justifyContent: "space-between",
            flexWrap: "wrap",
            gap: 12,
            marginBottom: 20,
          }}
        >
          <div>
            <h2 style={{ margin: "0 0 6px" }}>Order Management</h2>
            <small style={{ color: "#929db5" }}>
              Review and manage all purchase orders
            </small>
          </div>

          <div style={{ display: "flex", gap: 10, flexWrap: "wrap" }}>
            <input
              style={{ ...styles.input, width: 210 }}
              placeholder="Search orders..."
              value={search}
              onChange={(e) => setSearch(e.target.value)}
            />

            <select
              style={{ ...styles.input, width: 150 }}
              value={filter}
              onChange={(e) => setFilter(e.target.value)}
            >
              <option>All</option>
              <option>Pending</option>
              <option>Approved</option>
              <option>Rejected</option>
            </select>
          </div>
        </div>

        <div style={{ overflowX: "auto" }}>
          <table
            style={{
              width: "100%",
              borderCollapse: "collapse",
              minWidth: 850,
              textAlign: "left",
            }}
          >
            <thead>
              <tr style={{ color: "#9ba6bd", fontSize: 13 }}>
                {[
                  "ORDER ID",
                  "SUPPLIER",
                  "ITEM",
                  "AMOUNT",
                  "DELIVERY",
                  "STATUS",
                  "ACTIONS",
                ].map((heading) => (
                  <th
                    key={heading}
                    style={{
                      padding: "14px 10px",
                      borderBottom: "1px solid #30394d",
                    }}
                  >
                    {heading}
                  </th>
                ))}
              </tr>
            </thead>

            <tbody>
              {filteredOrders.map((order) => (
                <tr key={order.id}>
                  <td style={{ padding: 12, borderBottom: "1px solid #283247" }}>
                    <strong>{order.id}</strong>
                  </td>
                  <td style={{ padding: 12, borderBottom: "1px solid #283247" }}>
                    {order.supplier}
                  </td>
                  <td style={{ padding: 12, borderBottom: "1px solid #283247" }}>
                    {order.item}
                  </td>
                  <td style={{ padding: 12, borderBottom: "1px solid #283247" }}>
                    {money(order.amount)}
                  </td>
                  <td style={{ padding: 12, borderBottom: "1px solid #283247" }}>
                    {order.delivery}
                  </td>
                  <td style={{ padding: 12, borderBottom: "1px solid #283247" }}>
                    <span style={statusStyle(order.status)}>
                      {order.status}
                    </span>
                  </td>
                  <td style={{ padding: 12, borderBottom: "1px solid #283247" }}>
                    <div style={{ display: "flex", gap: 7 }}>
                      <button
                        style={{
                          ...styles.button,
                          padding: "7px 10px",
                          background: "#293650",
                        }}
                        onClick={() => setSelectedOrder(order)}
                      >
                        View
                      </button>
                      <button
                        style={{
                          ...styles.button,
                          padding: "7px 10px",
                          background: "#174d40",
                        }}
                        onClick={() => downloadPO(order)}
                      >
                        Download
                      </button>
                    </div>
                  </td>
                </tr>
              ))}

              {filteredOrders.length === 0 && (
                <tr>
                  <td
                    colSpan="7"
                    style={{
                      textAlign: "center",
                      padding: 30,
                      color: "#9ba6bd",
                    }}
                  >
                    No purchase orders found.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* Create order modal */}
      {showForm && (
        <div style={modalBackdrop}>
          <form
            onSubmit={createOrder}
            style={modalStyle}
          >
            <h2>Create Purchase Order</h2>
            <p style={{ color: "#929db5" }}>
              Enter the details for your new order.
            </p>

            <label>Supplier Name</label>
            <input
              required
              name="supplier"
              style={styles.input}
              placeholder="Enter supplier name"
              value={form.supplier}
              onChange={updateForm}
            />

            <label>Category</label>
            <select
              name="category"
              style={styles.input}
              value={form.category}
              onChange={updateForm}
            >
              <option>Technology</option>
              <option>Raw Materials</option>
              <option>Logistics</option>
              <option>Office Supplies</option>
            </select>

            <label>Item / Service</label>
            <input
              required
              name="item"
              style={styles.input}
              placeholder="What are you purchasing?"
              value={form.item}
              onChange={updateForm}
            />

            <div style={{ display: "flex", gap: 12 }}>
              <div style={{ flex: 1 }}>
                <label>Quantity</label>
                <input
                  required
                  min="1"
                  type="number"
                  name="quantity"
                  style={styles.input}
                  value={form.quantity}
                  onChange={updateForm}
                />
              </div>
              <div style={{ flex: 1 }}>
                <label>Total Amount (₹)</label>
                <input
                  required
                  min="1"
                  type="number"
                  name="amount"
                  style={styles.input}
                  placeholder="e.g. 50000"
                  value={form.amount}
                  onChange={updateForm}
                />
              </div>
            </div>

            <label>Expected Delivery Date</label>
            <input
              required
              type="date"
              name="delivery"
              min={new Date().toISOString().slice(0, 10)}
              style={styles.input}
              value={form.delivery}
              onChange={updateForm}
            />

            <div style={{ display: "flex", gap: 10, marginTop: 20 }}>
              <button type="submit" style={styles.button}>
                Create Order
              </button>
              <button
                type="button"
                style={{ ...styles.button, background: "#35405a" }}
                onClick={() => setShowForm(false)}
              >
                Cancel
              </button>
            </div>
          </form>
        </div>
      )}

      {/* Order details modal */}
      {selectedOrder && (
        <div style={modalBackdrop}>
          <div style={modalStyle}>
            <h2>Purchase Order Details</h2>
            <h3 style={{ color: "#a99fff" }}>{selectedOrder.id}</h3>

            {[
              ["Supplier", selectedOrder.supplier],
              ["Item", selectedOrder.item],
              ["Category", selectedOrder.category],
              ["Quantity", selectedOrder.quantity],
              ["Amount", money(selectedOrder.amount)],
              ["Order Date", selectedOrder.date],
              ["Delivery Date", selectedOrder.delivery],
              ["Approval Status", selectedOrder.status],
              ["Payment Status", selectedOrder.payment],
            ].map(([label, value]) => (
              <div
                key={label}
                style={{
                  display: "flex",
                  justifyContent: "space-between",
                  gap: 12,
                  padding: "10px 0",
                  borderBottom: "1px solid #30394d",
                }}
              >
                <span style={{ color: "#9ba6bd" }}>{label}</span>
                <strong>{value}</strong>
              </div>
            ))}

            {selectedOrder.status === "Pending" && (
              <div style={{ display: "flex", gap: 10, marginTop: 20 }}>
                <button
                  style={{ ...styles.button, background: "#16865f" }}
                  onClick={() => updateStatus(selectedOrder.id, "Approved")}
                >
                  Approve
                </button>
                <button
                  style={{ ...styles.button, background: "#b64256" }}
                  onClick={() => updateStatus(selectedOrder.id, "Rejected")}
                >
                  Reject
                </button>
              </div>
            )}

            <button
              style={{
                ...styles.button,
                background: "#35405a",
                marginTop: 15,
              }}
              onClick={() => setSelectedOrder(null)}
            >
              Close
            </button>
          </div>
        </div>
      )}
    </div>
  );
}

const modalBackdrop = {
  position: "fixed",
  inset: 0,
  background: "rgba(0,0,0,0.75)",
  display: "flex",
  alignItems: "center",
  justifyContent: "center",
  padding: 15,
  zIndex: 1000,
  overflowY: "auto",
};

const modalStyle = {
  background: "#151b2b",
  border: "1px solid #35405a",
  borderRadius: 16,
  padding: 25,
  width: "100%",
  maxWidth: 520,
  maxHeight: "90vh",
  overflowY: "auto",
  display: "flex",
  flexDirection: "column",
  gap: 12,
  color: "#e9edf7",
};
